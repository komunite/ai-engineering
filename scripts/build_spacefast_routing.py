#!/usr/bin/env python3
"""Generate the build-time part of site/_redirects and site/_headers for Spacefast.

Spacefast serves the site, but three of its defaults differ from how
Vercel served the same files. Every URL must keep answering exactly as
it did on Vercel, so this script papers over each difference:

1. Raw Markdown. Spacefast never serves a `*.md` URL: it renders each
   Markdown file into `<dir>/<name>/index.html` and answers the `.md`
   path with 404, and a rewrite cannot target a `.md` file. lesson.html
   fetches `phases/**/docs/tr.md`, and those URLs were public on Vercel.
   So every `X.md` gets a byte-identical `X.md.txt` copy, a forced
   pattern rewrite serves it at `X.md`, and a header rule restores
   `Content-Type: text/markdown`.

2. Rendered Markdown pages. The `<dir>/<name>/` pages Spacefast renders
   never existed on Vercel. Forced 404 rules keep them from becoming new
   duplicate-content URLs. Pattern rules cover the bulk; whatever a
   pattern does not cover gets an exact rule. The build fails if a 404
   pattern would shadow a real file or page.

3. Slash-less lesson URLs. Vercel answered both /phases/<p>/<l>/ and
   /phases/<p>/<l> with the lesson stub. Spacefast 308s the slash-less
   form of a directory before it consults non-forced rules, so each
   lesson gets an exact forced rewrite to its index.html.

Generated blocks sit between marker lines and are replaced on every run,
so the script is idempotent. Run AFTER build_lesson_pages.py, once
site/phases/ holds the copied curriculum and the lesson stubs:

    python3 scripts/build_spacefast_routing.py
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
REDIRECTS = SITE / "_redirects"
HEADERS = SITE / "_headers"

BEGIN = "# --- BEGIN generated by scripts/build_spacefast_routing.py ---"
END = "# --- END generated by scripts/build_spacefast_routing.py ---"

# Spacefast compiles at most 2000 static and 100 dynamic redirect rules.
MAX_STATIC_RULES = 2000
MAX_DYNAMIC_RULES = 100

# 404 patterns for rendered Markdown pages, checked against every real
# file and page below. Rendered paths none of these match get exact rules.
RENDERED_404_PATTERNS = [
    "/phases/:phase/README",
    "/phases/:phase/README.tr",
    "/phases/:phase/:lesson/mission",
    "/phases/:phase/:lesson/docs/:name",
    "/phases/:phase/:lesson/outputs/:name",
    "/phases/:phase/:lesson/outputs/:pack/docs/:name",
]

# Real files a 404 pattern may shadow: empty placeholders nobody links to.
SHADOW_ALLOWED = {".gitkeep"}


def pattern_regex(pattern: str) -> re.Pattern[str]:
    """Spacefast matcher grammar: `:name` is one segment, the rest is literal,
    and a trailing slash is optional."""
    out = []
    for part in re.split(r"(:[A-Za-z][A-Za-z0-9_]*)", pattern):
        out.append("[^/]+" if part.startswith(":") else re.escape(part))
    return re.compile("^" + "".join(out) + "/?$")


def replace_block(path: Path, lines: list[str]) -> None:
    existing = path.read_text(encoding="utf-8") if path.is_file() else ""
    if BEGIN in existing and END in existing:
        head, _, rest = existing.partition(BEGIN)
        _, _, tail = rest.partition(END)
        existing = head.rstrip("\n") + "\n" + tail.lstrip("\n")
    block = "\n".join([BEGIN, *lines, END])
    path.write_text(existing.rstrip("\n") + "\n\n" + block + "\n", encoding="utf-8")


def depth_pattern(depth: int, last: str) -> str:
    """`/:d1/:d2/<last>` with depth-1 directory placeholders."""
    return "".join(f"/:d{i}" for i in range(1, depth)) + "/" + last


def main() -> int:
    stubs = sorted(SITE.glob("phases/[0-9][0-9]-*/[0-9][0-9]-*/index.html"))
    if not stubs:
        print("spacefast routing: no lesson stubs under site/phases — run build_lesson_pages.py first", file=sys.stderr)
        return 1

    for stale in SITE.rglob("*.md.txt"):
        stale.unlink()
    markdown = sorted(SITE.rglob("*.md"))
    for md in markdown:
        shutil.copyfile(md, md.with_name(md.name + ".txt"))
    md_depths = sorted({len(md.relative_to(SITE).parts) for md in markdown})

    redirects: list[str] = []
    headers: list[str] = []
    static_rules = dynamic_rules = 0

    # 1. Raw Markdown, one forced pattern per directory depth.
    redirects.append("# Raw Markdown: serve X.md from its X.md.txt copy.")
    for depth in md_depths:
        source = depth_pattern(depth, ":name.md")
        redirects.append(f"{source}  {source}.txt  200!")
        headers.append(f"{source}\n  Content-Type: text/markdown; charset=utf-8")
        dynamic_rules += 1

    # 2. Slash-less lesson URLs.
    redirects.append("")
    redirects.append("# Slash-less lesson URLs: 200 with the stub, as on Vercel.")
    for stub in stubs:
        lesson_url = "/" + stub.parent.relative_to(SITE).as_posix()
        redirects.append(f"{lesson_url}  {lesson_url}/index.html  200!")
        static_rules += 1

    # 3. Rendered Markdown pages answer 404. `.md` URLs are answered by the
    # rewrites above (first match wins), and the `.md.txt` copies are only
    # rewrite targets, so neither counts as a shadowed route.
    real_routes = [
        "/" + p.relative_to(SITE).as_posix()
        for p in SITE.rglob("*")
        if p.is_file() and not p.name.endswith((".md", ".md.txt"))
    ]
    real_routes += ["/" + p.parent.relative_to(SITE).as_posix() for p in SITE.rglob("index.html")]
    compiled = [(p, pattern_regex(p)) for p in RENDERED_404_PATTERNS]
    for pattern, rx in compiled:
        shadowed = [r for r in real_routes if rx.match(r) and Path(r).name not in SHADOW_ALLOWED]
        if shadowed:
            print(f"spacefast routing: 404 pattern {pattern} would shadow real routes, e.g. {shadowed[:3]}", file=sys.stderr)
            return 1

    redirects.append("")
    redirects.append("# Pages Spacefast renders from Markdown never existed on Vercel: 404.")
    for pattern in RENDERED_404_PATTERNS:
        redirects.append(f"{pattern}  /404  404!")
        dynamic_rules += 1
    for md in markdown:
        rel = md.relative_to(SITE).with_suffix("").as_posix()
        rendered = "/" + rel
        if not any(rx.match(rendered) for _, rx in compiled):
            redirects.append(f"{rendered}  /404  404!")
            static_rules += 1

    if static_rules > MAX_STATIC_RULES or dynamic_rules > MAX_DYNAMIC_RULES:
        print(f"spacefast routing: {static_rules} static / {dynamic_rules} dynamic rules exceed Spacefast limits", file=sys.stderr)
        return 1

    replace_block(REDIRECTS, redirects)
    replace_block(HEADERS, headers)
    print(f"spacefast routing: {len(markdown)} markdown copies, {static_rules} static + {dynamic_rules} dynamic rules")
    return 0


if __name__ == "__main__":
    sys.exit(main())
